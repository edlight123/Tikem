#!/usr/bin/env bash
# Frees regenerable space only: caches, build output, merged agent worktrees.
# Nothing here is a user file; everything rebuilds itself on next use.
#   bash scripts/free-disk-space.sh
set -u
before=$(df -g / | awk 'NR==2{print $4}')

npm cache clean --force >/dev/null 2>&1          # ~4 GB npm download cache
rm -rf ~/Library/Caches/* 2>/dev/null             # ~3.5 GB app caches
rm -rf "$HOME/Library/Application Support/Google/Chrome/OptGuideOnDeviceModel"  # ~4 GB Chrome on-device AI model
rm -rf ~/.cache/puppeteer ~/.cache/uv             # ~0.7 GB test-browser/py caches
rm -rf ~/Tikem/mobile/ios                         # ~1 GB generated iOS build (regenerated by expo run:ios / EAS)
rm -rf ~/rotaractnyc-work/.next                   # ~0.8 GB Next.js build output

cd ~/Tikem && for w in .claude/worktrees/agent-a4787af9bf261fc03 .claude/worktrees/agent-a705a8b8089c23b7f; do
  [ -d "$w" ] && git worktree remove "$w"         # merged + clean (checked)
done
git -C ~/Tikem worktree prune

after=$(df -g / | awk 'NR==2{print $4}')
echo "Free space: ${before} GB -> ${after} GB"
