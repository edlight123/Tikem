#!/usr/bin/env node
/**
 * Regenerates lib/wallet/brandArt.ts from mobile/assets/icon.png (the app
 * icon: cream "t" + teal dot on #0A0A0A). The pass logo is that mark keyed
 * onto transparency and trimmed; the pass icon is the app icon itself.
 *
 *   node scripts/build-wallet-brand-art.mjs
 */
import { writeFileSync } from 'node:fs'
import sharp from 'sharp'

const SRC = new URL('../mobile/assets/icon.png', import.meta.url).pathname
const BG = [10, 10, 10]
// Distance from the background at which a pixel counts as fully opaque art.
const SOLID = 90

async function keyedMark() {
  const { data, info } = await sharp(SRC).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  for (let i = 0; i < data.length; i += 4) {
    const d = Math.hypot(data[i] - BG[0], data[i + 1] - BG[1], data[i + 2] - BG[2])
    const a = Math.min(1, d / SOLID)
    if (a === 0) {
      data[i + 3] = 0
      continue
    }
    // Un-mix the background from anti-aliased edges so they don't go grey.
    for (let c = 0; c < 3; c++) {
      data[i + c] = Math.max(0, Math.min(255, Math.round((data[i + c] - BG[c] * (1 - a)) / a)))
    }
    data[i + 3] = Math.round(a * 255)
  }
  return sharp(data, { raw: { width: info.width, height: info.height, channels: 4 } }).trim().png().toBuffer()
}

const mark = await keyedMark()
// Apple's logo slot is at most 160x50pt; the mark is drawn 40pt tall.
const logo = (h) => sharp(mark).resize({ height: h }).png({ compressionLevel: 9 }).toBuffer()
const icon = (s) => sharp(SRC).resize(s, s).png({ compressionLevel: 9 }).toBuffer()
const [logo1, logo2, logo3, icon1, icon2, icon3] = await Promise.all([
  logo(40), logo(80), logo(120), icon(29), icon(58), icon(87),
])
const b = (x) => JSON.stringify(x.toString('base64'))
writeFileSync(
  new URL('../lib/wallet/brandArt.ts', import.meta.url),
  `/**
 * GENERATED by scripts/build-wallet-brand-art.mjs from mobile/assets/icon.png.
 * The Tikèm "t" mark on transparency (pass header logo) and the app icon (pass
 * icon). Do not edit by hand.
 */
const png = (b64: string) => Buffer.from(b64, 'base64')

export const PASS_LOGO = { x1: png(${b(logo1)}), x2: png(${b(logo2)}), x3: png(${b(logo3)}) }
export const PASS_ICON = { x1: png(${b(icon1)}), x2: png(${b(icon2)}), x3: png(${b(icon3)}) }
`
)
writeFileSync('/private/tmp/claude-501/-Users-tedjacquet-Tikem/205f1298-7a53-4169-9af3-23d41fca649f/scratchpad/w/logo-preview.png',
  await sharp({ create: { width: 400, height: 200, channels: 3, background: '#3a2a20' } })
    .composite([{ input: await logo(120), top: 40, left: 40 }]).png().toBuffer())
